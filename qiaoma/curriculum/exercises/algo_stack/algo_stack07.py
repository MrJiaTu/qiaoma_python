# ============================================================
# 【题目】对每个元素找右侧第一个比它大的数，没有则 -1：[2,1,2,4,3] → [4,2,4,-1,-1]。
# 【要求】用单调栈实现 next_greater(nums)。
# 【完成】修好后删除文件里的未完成标记行。
