# 我还没做完
def next_greater(nums):
    result = [-1] * len(nums)
    for i in range(len(nums)):  # 暴力向右扫，O(n^2)
        for j in range(i + 1, len(nums)):
            if nums[j] > nums[i]:
                result[i] = nums[j]
                break
    return result
