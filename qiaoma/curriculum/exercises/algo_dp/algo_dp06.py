# 我还没做完
def lis(nums):
    if not nums:
        return 0
    dp = [1] * len(nums)
    for i in range(len(nums)):
        for j in range(i):
            if nums[j] < nums[i]:
                dp[i] = dp[j]  # 没 +1 也没取 max
    return max(dp)
