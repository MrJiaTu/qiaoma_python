def is_valid(s):
    stack = []
    pairs = {")": "(", "]": "[", "}": "{"}
    for ch in s:
        if ch in pairs.values():
            stack.append(ch)
        else:
            stack.pop()  # 空栈会崩，也没比对
    return True
