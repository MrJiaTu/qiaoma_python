def knapsack(items, capacity):
    dp = [0] * (capacity + 1)
    for w, v in items:
        for c in range(w, capacity + 1):  # 正序会变成完全背包
            dp[c] = max(dp[c], dp[c - w] + v)
    return dp[capacity]
